/**
 * Make the harness packages resolvable from this repository.
 *
 * The plugin imports `@deepseek-ai/dsh-tools` and (through its own loader)
 * `sharp`. Neither is a dependency a contributor would `npm install`: `sharp`
 * belongs to the harness, and `@deepseek-ai/*` packages only exist inside a DSH
 * installation. A real deployment resolves both because the plugin is installed
 * into a profile whose tree hoists them.
 *
 * This reproduces that resolution without an import hook and without symlinks
 * (which need privileges this may not have): for each package it writes a tiny
 * `node_modules` entry that re-exports the package's *real* files by absolute
 * URL. Re-exporting rather than copying matters — Node loads the real file once,
 * so the `@deepseek-ai/cordis` instance the plugin sees is the same instance the
 * harness packages use, and Cordis identifies services by instance.
 *
 * Nothing is written when a real installation is already present: a contributor
 * who ran `npm install` keeps their own copy.
 *
 * Set `DSH_HARNESS_MODULES` to the directory holding the `@deepseek-ai/*`
 * packages (for a global npm install: `<npm root -g>/@deepseek-ai/dsh/node_modules`).
 *
 * @module test/integration/link-modules
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve, sep } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')

/** Packages the harness imports directly. Their own dependencies come from the DSH tree. */
const LINKED = [
  'sharp',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-tools',
  '@deepseek-ai/dsh-fs-local',
  '@deepseek-ai/dsh-attachment-local',
  '@deepseek-ai/dsh-system-prompt',
  '@deepseek-ai/dsh-util-values',
  '@deepseek-ai/dsh-llm',
]

/** Marker written beside a generated entry, so only our own files are ever replaced. */
const MARKER = '.dsh-read-animation-shim'

/**
 * Locate the DSH package tree.
 * @returns the absolute directory containing `@deepseek-ai/*`, or undefined.
 */
export function findHarnessModules() {
  const fromEnv = process.env.DSH_HARNESS_MODULES
  if (typeof fromEnv !== 'string' || fromEnv.trim().length === 0) return undefined
  const candidate = resolve(fromEnv.trim())
  return existsSync(join(candidate, '@deepseek-ai', 'dsh-tools')) ? candidate : undefined
}

/**
 * Create (or refresh) the `node_modules` entries this harness needs.
 * @param modulesRoot - the directory containing `@deepseek-ai/*` and `sharp`.
 * @returns the list of entries created, for the caller to report.
 */
export function ensureHarnessModules(modulesRoot) {
  const created = []
  for (const name of LINKED) {
    const source = join(modulesRoot, ...name.split('/'))
    if (!existsSync(join(source, 'package.json'))) throw new Error(`${name} was not found under ${modulesRoot}`)

    const target = join(REPO, 'node_modules', ...name.split('/'))
    if (existsSync(target) && !existsSync(join(target, MARKER))) continue

    if (existsSync(target)) rmSync(target, { recursive: true, force: true })
    mkdirSync(target, { recursive: true })

    const { esm, cjs } = entriesOf(source)
    writeFileSync(
      join(target, 'package.json'),
      `${JSON.stringify(
        {
          name,
          version: '0.0.0-dsh-read-animation-shim',
          private: true,
          type: 'module',
          main: './index.cjs',
          exports: { '.': { import: './index.mjs', require: './index.cjs' } },
        },
        null,
        2,
      )}\n`,
    )
    const esmUrl = pathToFileURL(esm).href
    writeFileSync(
      join(target, 'index.mjs'),
      `// Generated by test/integration/link-modules.mjs — re-exports the real package.\n` +
        `import * as namespace from ${JSON.stringify(esmUrl)}\n` +
        `export * from ${JSON.stringify(esmUrl)}\n` +
        `export default namespace.default\n`,
    )
    writeFileSync(join(target, 'index.cjs'), `module.exports = require(${JSON.stringify(cjs)})\n`)
    writeFileSync(join(target, MARKER), `${source}\n`)
    created.push(name)
  }
  return created
}

/**
 * Resolve a package's ESM and CommonJS entry points from its own manifest.
 * @param source - absolute package directory.
 * @returns absolute paths to both entries.
 */
function entriesOf(source) {
  const manifest = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'))
  const root = manifest.exports === undefined ? undefined : (manifest.exports['.'] ?? manifest.exports)
  return {
    esm: join(source, firstString(root?.import ?? root?.default ?? root?.require) ?? manifest.main ?? 'index.js'),
    cjs: join(source, firstString(root?.require ?? root?.default ?? root?.import) ?? manifest.main ?? 'index.js'),
  }
}

/** Walk a conditional-exports value down to its first plain string. */
function firstString(value) {
  if (typeof value === 'string') return value.replace(/^\.\//, '')
  if (value !== null && typeof value === 'object') {
    for (const key of ['default', 'import', 'require', 'node']) {
      const found = firstString(value[key])
      if (found !== undefined) return found
    }
  }
  return undefined
}
